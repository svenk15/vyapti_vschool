export const financeCapabilities=['SUMMARY_READ','EXCEPTION_REQUEST','EXCEPTION_REVIEW'] as const;
export type FinanceCapability=typeof financeCapabilities[number];
export type FinanceCurrency='INR'|string;
export type FinanceMoney=Readonly<{currency:FinanceCurrency;minorUnits:string}>;
export const formatFinanceMoney=(currency:string,minorUnits:string,locale='en-IN')=>new Intl.NumberFormat(locale,{style:'currency',currency}).format(Number(minorUnits)/100);
export type FinanceActor=Readonly<{accountId:string;displayName:string}>;
export type FinanceReviewer=FinanceActor&Readonly<{currency:string;approvalLimitMinor:string}>;
export type FinanceReconciliationState='RECONCILED'|'UNRECONCILED';
export type FinanceSummary=Readonly<{
 reconciliationId:string;
 currency:string;
 cutoffAt:string;
 state:FinanceReconciliationState;
 definitionVersion:number;
 sourceDigestPrefix:string;
 charge:FinanceMoney;
 payment:FinanceMoney;
 allocated:FinanceMoney;
 unmatchedCharge:FinanceMoney;
 unallocatedPayment:FinanceMoney;
 exceptionCount:number;
 syntheticOnly:true;
}>;
export type FinanceExceptionKind='CONCESSION'|'REFUND_REQUEST';
export type FinanceExceptionState='PENDING'|'APPROVED'|'REJECTED';
export type FinanceExceptionSummary=Readonly<{
 id:string;
 reference:string;
 reconciliationId:string;
 currency:string;
 kind:FinanceExceptionKind;
 amountMinor:string;
 reason:string;
 state:FinanceExceptionState;
 version:number;
 requester:FinanceActor;
 reviewer:FinanceActor;
 requestedAt:string;
 updatedAt:string;
 role:'REQUESTER'|'REVIEWER';
}>;
export type FinanceExceptionDetail=FinanceExceptionSummary&Readonly<{
 reconciliation:FinanceSummary;
 decisionReason:string|null;
 decidedAt:string|null;
 history:readonly Readonly<{number:number;type:'REQUESTED'|'APPROVED'|'REJECTED';fromState:FinanceExceptionState|null;toState:FinanceExceptionState;actor:FinanceActor;reason:string|null;exceptionVersion:number;occurredAt:string}>[];
 can:Readonly<{approve:boolean;reject:boolean}>;
 consequence:'APPROVAL_ONLY_NO_PAYMENT_OR_LEDGER_CHANGE';
}>;
export type FinanceCommandResult=Readonly<{exceptionId:string;state:FinanceExceptionState;version:number;replayed:boolean}>;
export type FinanceCommandStatus=Readonly<{state:'UNKNOWN'}>|Readonly<{state:'FOUND';result:FinanceCommandResult}>|Readonly<{state:'CHANGED';currentVersion:number;currentState:FinanceExceptionState}>;
