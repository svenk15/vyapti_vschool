CREATE TABLE "vs_attendance_session" (
  "id" UUID NOT NULL,
  "organization_id" UUID NOT NULL,
  "school_id" UUID NOT NULL,
  "offering_id" UUID NOT NULL,
  "school_date" DATE NOT NULL,
  "starts_at" TIMESTAMPTZ(3) NOT NULL,
  "ends_at" TIMESTAMPTZ(3) NOT NULL,
  "occurrence_key" VARCHAR(80) NOT NULL,
  "calendar_revision_id" UUID NOT NULL,
  "status" VARCHAR(20) NOT NULL,
  "version" INTEGER NOT NULL,
  "roster_revision" CHAR(64),
  "opened_at" TIMESTAMPTZ(3),
  "submitted_at" TIMESTAMPTZ(3),
  "submitted_by" UUID,
  "cancelled_at" TIMESTAMPTZ(3),
  CONSTRAINT "vs_attendance_session_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "vs_attendance_session_scope_id_key" UNIQUE ("organization_id", "school_id", "id"),
  CONSTRAINT "vs_attendance_session_occurrence_key" UNIQUE ("organization_id", "school_id", "offering_id", "occurrence_key"),
  CONSTRAINT "vs_attendance_session_school_fkey" FOREIGN KEY ("organization_id", "school_id") REFERENCES "vs_access_school" ("organization_id", "id") ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT "vs_attendance_session_offering_fkey" FOREIGN KEY ("organization_id", "school_id", "offering_id") REFERENCES "vs_academics_course_offering" ("organization_id", "school_id", "id") ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT "vs_attendance_session_calendar_revision_fkey" FOREIGN KEY ("organization_id", "school_id", "calendar_revision_id") REFERENCES "vs_academics_calendar_revision" ("organization_id", "school_id", "id") ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT "vs_attendance_session_submitted_by_fkey" FOREIGN KEY ("submitted_by") REFERENCES "vs_access_user_account" ("id") ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT "vs_attendance_session_time_check" CHECK ("starts_at" < "ends_at"),
  CONSTRAINT "vs_attendance_session_version_check" CHECK ("version" >= 1),
  CONSTRAINT "vs_attendance_session_status_check" CHECK ("status" IN ('SCHEDULED','OPEN','SUBMITTED','CANCELLED'))
);
CREATE INDEX "vs_attendance_session_school_day_idx" ON "vs_attendance_session" ("organization_id", "school_id", "school_date", "status", "starts_at", "id");
